package com.arianegraphql.ktx

import com.arianegraphql.server.resolver.BatchResolverEnvironment
import com.arianegraphql.server.resolver.FunctionalResolver
import com.arianegraphql.server.resolver.Resolver
import com.arianegraphql.server.resolver.ResolverContext

/**
 * Typed reference to a field of a GraphQL root type (Mutation, Subscription), generated
 * by the codegen plugin.
 *
 * A field reference carries the source, argument and return types of the field; the
 * registration behavior lives here, in the core library, so that generated code keeps
 * the same shape when the resolver API evolves.
 */
open class RootFieldRef<S, A, R>(
    internal val builder: TypeResolverBuilder<S>,
    val name: String,
    internal val argumentType: Class<A>,
) {

    /** Registers a resolver implementation for this field. */
    operator fun invoke(resolver: Resolver<S, A, R>) {
        builder.resolve(name, argumentType, resolver)
    }

    /** Registers a lambda resolver for this field. */
    operator fun invoke(resolver: suspend ResolverContext<S>.(A) -> R) {
        builder.resolve(name, argumentType, FunctionalResolver(resolver))
    }
}

/**
 * Typed reference to a field of a GraphQL object type (including Query), generated by
 * the codegen plugin. In addition to plain resolvers, the field can be resolved in
 * batch to solve N+1 queries.
 */
class FieldRef<S, A, R>(
    builder: TypeResolverBuilder<S>,
    name: String,
    argumentType: Class<A>,
) : RootFieldRef<S, A, R>(builder, name, argumentType) {

    /**
     * Registers a batch resolver for this field, solving N+1 queries through a
     * DataLoader created and registered automatically for each request.
     *
     * Keys extracted by [key] from every occurrence of the field are collected,
     * deduplicated and handed to [loader] in a single call per execution level.
     * Keys missing from the returned map resolve to null.
     */
    fun <K : Any> batch(
        key: (A, S) -> K,
        loader: suspend BatchResolverEnvironment<S, A, K>.(keys: Set<K>) -> Map<K, R>,
    ) {
        builder.resolveBatch(name, argumentType, key, loader)
    }
}
